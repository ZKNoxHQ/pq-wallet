// Generates src/abi/*.ts from the Foundry artifacts in contracts/out. Never edit the output by hand.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../../../contracts/out");
const dst = join(here, "../src/abi");
mkdirSync(dst, { recursive: true });

const contracts = {
  ZKNOX_PQAccount7702: "ZKNOX_PQAccount7702.sol",
  ZKNOX_PQSatellite7702: "ZKNOX_PQSatellite7702.sol",
  ZKNOX_PQFactory7702: "ZKNOX_PQFactory7702.sol",
  ZKNOX_dilithium: "ZKNOX_dilithium.sol",
  ZKNOX_falcon8_verifier: "ZKNOX_falcon8_verifier.sol",
  ECDSAk1Verifier: "VerifierECDSAk1.sol",
  EntryPoint: "EntryPoint.sol",
};
const index = [];
for (const [name, file] of Object.entries(contracts)) {
  const artifact = JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
  const body = `// generated by scripts/gen-abi.mjs from contracts/out/${file}/${name}.json\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(dst, `${name}.ts`), body);
  index.push(`export { ${name}Abi } from "./${name}";`);
}
writeFileSync(join(dst, "index.ts"), index.join("\n") + "\n");
console.log("abi:", Object.keys(contracts).join(", "));
